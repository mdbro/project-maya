#!/usr/bin/env python3
"""Derive diagnostic old Q2 bodies; frozen originals remain unchanged.

Only namespace/include renames, default-off template/pointer parameters and
post-reduction snapshot writes are inserted. No numerical expression is edited.
Run from any directory; generated hashes and source hashes are recorded.
"""
from pathlib import Path
import hashlib
import json

HERE = Path(__file__).resolve().parent


def replace_once(text, before, after):
    if text.count(before) != 1:
        raise RuntimeError(f"expected one transform anchor, got {text.count(before)}: {before!r}")
    return text.replace(before, after)


def transform(name):
    source = (HERE / name).read_text()
    text = (source.replace("helper_tc_frozen", "helper_tc_raw_frozen")
            .replace("helper_q_frozen", "helper_q_raw_frozen")
            .replace("helper_dp_frozen", "helper_dp_raw_frozen"))
    if name == "helper_q_frozen.cuh":
        start = text.index("template <int S, int P, bool Expanded = false>\n__device__ __forceinline__ void up2_block")
        end = text.index("template <int S, int P, bool Expanded = false>\n__global__", start)
        body = text[start:end]
        body = replace_once(body, "template <int S, int P, bool Expanded = false>", "template <int S, int P, bool Expanded = false, bool Raw = false>")
        body = replace_once(body, "std::uint8_t* workspace, int j, int pair) {", "std::uint8_t* workspace, int j, int pair, float* raw = nullptr) {")
        anchor = "        const float u0 = __shfl_xor_sync(0xffffffffu, s0, 4), u1 = __shfl_xor_sync(0xffffffffu, s1, 4);"
        sink = """        if constexpr (Raw) {
            const std::size_t out = ((std::size_t(j) * (2 * kI / 16) + group) * 32 + lane) * 4;
            raw[out] = s0; raw[out + 1] = s1; raw[out + 2] = s2; raw[out + 3] = s3;
        }
"""
    else:
        start = text.index("template<int S, bool Down, int P>\n__device__ __forceinline__ void project2_block")
        end = text.index("template<int S, bool Down, int P>\n__global__", start)
        body = text[start:end]
        body = replace_once(body, "template<int S, bool Down, int P>", "template<int S, bool Down, int P, bool Raw = false>")
        body = replace_once(body, "int j, int group) {", "int j, int group, float* raw = nullptr) {")
        anchor = "    if constexpr (Down) {"
        sink = """    if constexpr (Raw) {
        const std::size_t out = ((std::size_t(j) * ((Down ? kH : 2 * kI) / 16) + group) * 32 + lane) * 4;
        raw[out] = s0; raw[out + 1] = s1; raw[out + 2] = s2; raw[out + 3] = s3;
    }
"""
    body = replace_once(body, anchor, sink + anchor)
    text = "// Generated by make_helper_raw_reference.py; diagnostic snapshots only.\n" + text[:start] + body + text[end:]
    destination = name.replace("_frozen", "_raw_frozen")
    (HERE / destination).write_text(text)
    return destination, {"source": name, "source_sha256": hashlib.sha256(source.encode()).hexdigest(),
                         "generated_sha256": hashlib.sha256(text.encode()).hexdigest()}


if __name__ == "__main__":
    manifest = {"source_commit": json.loads((HERE / "helper_frozen_manifest.json").read_text())["source_commit"],
                "transforms": "namespace/include renames; default-off Raw template and pointer; accumulator snapshot after original reduction",
                "files": dict(transform(n) for n in ("helper_tc_frozen.cuh", "helper_q_frozen.cuh"))}
    (HERE / "helper_raw_manifest.json").write_text(json.dumps(manifest, indent=2) + "\n")
